-- cortex.namespaces: the levels that hold objects, each under its parent or at the top: a MySQL database; a PostgreSQL database and its schemas. Owner: cortex.
CREATE TABLE cortex.namespaces (
  id        BIGINT NOT NULL PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,                              -- issued by the database, kept when the name changes
  parent    BIGINT REFERENCES cortex.namespaces (id) ON DELETE CASCADE DEFERRABLE INITIALLY DEFERRED,  -- the namespace it sits in; NULL at the top
  name      TEXT NOT NULL CHECK (length(name) >= 1),                                                   -- sales
  position  NUMERIC NOT NULL UNIQUE CHECK (position > 0),                                              -- its place among the namespaces, in the order made or read; an order key
  comment   TEXT,                                                                                      -- what it holds: written into its SQL
  UNIQUE NULLS NOT DISTINCT (parent, name) DEFERRABLE INITIALLY DEFERRED
);

COMMENT ON TABLE cortex.namespaces IS 'the levels that hold objects, each under its parent or at the top: a MySQL database; a PostgreSQL database and its schemas.';
COMMENT ON COLUMN cortex.namespaces.id IS 'issued by the database, kept when the name changes';
COMMENT ON COLUMN cortex.namespaces.parent IS 'the namespace it sits in; NULL at the top';
COMMENT ON COLUMN cortex.namespaces.name IS 'sales';
COMMENT ON COLUMN cortex.namespaces.position IS 'its place among the namespaces, in the order made or read; an order key';
COMMENT ON COLUMN cortex.namespaces.comment IS 'what it holds: written into its SQL';
