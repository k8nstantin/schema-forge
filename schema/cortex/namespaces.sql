-- cortex.namespaces: the levels that hold objects, each under its parent or at the top: a MySQL database; a PostgreSQL database and its schemas. Owner: cortex.
CREATE TABLE cortex.namespaces (
  id        BIGINT NOT NULL PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,                                  -- issued by the database, kept when the name changes
  design    UUID NOT NULL REFERENCES cortex.designs (id) ON DELETE CASCADE DEFERRABLE INITIALLY DEFERRED,  -- the design it belongs to
  parent    BIGINT,                                                                                        -- the namespace it sits in, of the same design; NULL at the top
  name      TEXT NOT NULL CHECK (length(name) >= 1),                                                       -- sales
  position  NUMERIC NOT NULL CHECK (position > 0),                                                         -- its place among its design's namespaces, in the order made or read; an order key
  comment   TEXT,                                                                                          -- what it holds: written into its SQL
  UNIQUE NULLS NOT DISTINCT (design, parent, name) DEFERRABLE INITIALLY DEFERRED,
  UNIQUE (design, position) DEFERRABLE INITIALLY DEFERRED,
  UNIQUE (design, id),
  FOREIGN KEY (design, parent) REFERENCES cortex.namespaces (design, id) ON DELETE CASCADE DEFERRABLE INITIALLY DEFERRED
);

CREATE INDEX namespaces_parent ON cortex.namespaces (design, parent);

COMMENT ON TABLE cortex.namespaces IS 'the levels that hold objects, each under its parent or at the top: a MySQL database; a PostgreSQL database and its schemas.';
COMMENT ON COLUMN cortex.namespaces.id IS 'issued by the database, kept when the name changes';
COMMENT ON COLUMN cortex.namespaces.design IS 'the design it belongs to';
COMMENT ON COLUMN cortex.namespaces.parent IS 'the namespace it sits in, of the same design; NULL at the top';
COMMENT ON COLUMN cortex.namespaces.name IS 'sales';
COMMENT ON COLUMN cortex.namespaces.position IS 'its place among its design''s namespaces, in the order made or read; an order key';
COMMENT ON COLUMN cortex.namespaces.comment IS 'what it holds: written into its SQL';
