-- cortex.dependencies: what an object uses: a view's tables, a MERGE table's tables, a routine's tables where the engine says. A used object cannot be dropped before what uses it, and an edit names what it would break; a body is text, so a rename never reaches into it. Owner: cortex.
CREATE TABLE cortex.dependencies (
  id        BIGINT NOT NULL PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,                                  -- issued by the database
  design    UUID NOT NULL REFERENCES cortex.designs (id) ON DELETE CASCADE DEFERRABLE INITIALLY DEFERRED,  -- the design it belongs to
  object    BIGINT NOT NULL,                                                                               -- the object that uses
  uses      BIGINT NOT NULL,                                                                               -- the object used: it cannot go while this row is here
  position  INTEGER NOT NULL CHECK (position >= 1),                                                        -- its place, 1 first
  UNIQUE (object, uses) DEFERRABLE INITIALLY DEFERRED,
  CHECK (object <> uses),
  UNIQUE (design, id),
  FOREIGN KEY (design, object) REFERENCES cortex.objects (design, id) ON DELETE CASCADE DEFERRABLE INITIALLY DEFERRED,
  FOREIGN KEY (design, uses) REFERENCES cortex.objects (design, id) DEFERRABLE INITIALLY DEFERRED
);

CREATE INDEX dependencies_object ON cortex.dependencies (design, object);
CREATE INDEX dependencies_uses ON cortex.dependencies (design, uses);

COMMENT ON TABLE cortex.dependencies IS 'what an object uses: a view''s tables, a MERGE table''s tables, a routine''s tables where the engine says. A used object cannot be dropped before what uses it, and an edit names what it would break; a body is text, so a rename never reaches into it.';
COMMENT ON COLUMN cortex.dependencies.id IS 'issued by the database';
COMMENT ON COLUMN cortex.dependencies.design IS 'the design it belongs to';
COMMENT ON COLUMN cortex.dependencies.object IS 'the object that uses';
COMMENT ON COLUMN cortex.dependencies.uses IS 'the object used: it cannot go while this row is here';
COMMENT ON COLUMN cortex.dependencies.position IS 'its place, 1 first';
