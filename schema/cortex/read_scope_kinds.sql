-- cortex.read_scope_kinds: a kind of object a choice reads, as the design's engine names its kinds (table, view, procedure); a choice that lists none reads every kind of the objects it lists. Owner: cortex.
CREATE TABLE cortex.read_scope_kinds (
  id      BIGINT NOT NULL PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,                                  -- issued by the database
  design  UUID NOT NULL REFERENCES cortex.designs (id) ON DELETE CASCADE DEFERRABLE INITIALLY DEFERRED,  -- the design it belongs to
  scope   BIGINT NOT NULL,                                                                               -- the choice
  kind    TEXT NOT NULL CHECK (kind ~ '^[a-z0-9_]+$'),                                                   -- one of the design's engine's kinds (table)
  UNIQUE (scope, kind),
  UNIQUE (design, id),
  FOREIGN KEY (design, scope) REFERENCES cortex.read_scopes (design, id) ON DELETE CASCADE DEFERRABLE INITIALLY DEFERRED
);

CREATE INDEX read_scope_kinds_scope ON cortex.read_scope_kinds (design, scope);

COMMENT ON TABLE cortex.read_scope_kinds IS 'a kind of object a choice reads, as the design''s engine names its kinds (table, view, procedure); a choice that lists none reads every kind of the objects it lists.';
COMMENT ON COLUMN cortex.read_scope_kinds.id IS 'issued by the database';
COMMENT ON COLUMN cortex.read_scope_kinds.design IS 'the design it belongs to';
COMMENT ON COLUMN cortex.read_scope_kinds.scope IS 'the choice';
COMMENT ON COLUMN cortex.read_scope_kinds.kind IS 'one of the design''s engine''s kinds (table)';
