-- cortex.read_scope_objects: an object a choice reads, by its namespace and a name or a pattern, as the server names them; a choice that lists none reads every object of the kinds it lists. Owner: cortex.
CREATE TABLE cortex.read_scope_objects (
  id              BIGINT NOT NULL PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,                                  -- issued by the database
  design          UUID NOT NULL REFERENCES cortex.designs (id) ON DELETE CASCADE DEFERRABLE INITIALLY DEFERRED,  -- the design it belongs to
  scope           BIGINT NOT NULL,                                                                               -- the choice
  namespace_name  TEXT NOT NULL CHECK (length(namespace_name) >= 1),                                             -- the namespace, as the server names it (shop)
  pattern         TEXT NOT NULL CHECK (length(pattern) >= 1),                                                    -- a name, or a pattern in which % is any run of characters and _ one character, as LIKE takes them (orders, order%)
  position        NUMERIC NOT NULL CHECK (position > 0),                                                         -- its place in the choice, as the person listed them; an order key
  UNIQUE (scope, namespace_name, pattern),
  UNIQUE (scope, position),
  UNIQUE (design, id),
  FOREIGN KEY (design, scope) REFERENCES cortex.read_scopes (design, id) ON DELETE CASCADE DEFERRABLE INITIALLY DEFERRED
);

CREATE INDEX read_scope_objects_scope ON cortex.read_scope_objects (design, scope);

COMMENT ON TABLE cortex.read_scope_objects IS 'an object a choice reads, by its namespace and a name or a pattern, as the server names them; a choice that lists none reads every object of the kinds it lists.';
COMMENT ON COLUMN cortex.read_scope_objects.id IS 'issued by the database';
COMMENT ON COLUMN cortex.read_scope_objects.design IS 'the design it belongs to';
COMMENT ON COLUMN cortex.read_scope_objects.scope IS 'the choice';
COMMENT ON COLUMN cortex.read_scope_objects.namespace_name IS 'the namespace, as the server names it (shop)';
COMMENT ON COLUMN cortex.read_scope_objects.pattern IS 'a name, or a pattern in which % is any run of characters and _ one character, as LIKE takes them (orders, order%)';
COMMENT ON COLUMN cortex.read_scope_objects.position IS 'its place in the choice, as the person listed them; an order key';
