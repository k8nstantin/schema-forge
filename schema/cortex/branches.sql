-- cortex.branches: a line of work: its newest turn. Switching branch moves the design to its newest turn. Owner: cortex.
CREATE TABLE cortex.branches (
  id       BIGINT NOT NULL PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,  -- issued by the database
  name     TEXT NOT NULL UNIQUE CHECK (length(name) >= 1),                -- main, experiment
  head     UUID,                                                          -- its newest turn (a rule holds it to one: turns name their branch, so a key here would be a cycle); NULL before its first
  current  BOOLEAN NOT NULL DEFAULT false,                                -- true for the branch the design is on
  CHECK (current IS NOT DISTINCT FROM true OR NOT current)
);

CREATE UNIQUE INDEX branches_one_current ON cortex.branches (current) WHERE current;

COMMENT ON TABLE cortex.branches IS 'a line of work: its newest turn. Switching branch moves the design to its newest turn.';
COMMENT ON COLUMN cortex.branches.id IS 'issued by the database';
COMMENT ON COLUMN cortex.branches.name IS 'main, experiment';
COMMENT ON COLUMN cortex.branches.head IS 'its newest turn (a rule holds it to one: turns name their branch, so a key here would be a cycle); NULL before its first';
COMMENT ON COLUMN cortex.branches.current IS 'true for the branch the design is on';
