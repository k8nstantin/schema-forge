-- The live read's shop, in PostgreSQL: the same tables, view, routine, trigger and rows as the MySQL sample.
CREATE SCHEMA shop;
CREATE TABLE shop.customers (id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, email varchar(100) NOT NULL UNIQUE,
  country char(2), created timestamp);
CREATE INDEX k_country ON shop.customers (country);
CREATE INDEX k_created_unused ON shop.customers (created);
CREATE TABLE shop.products (id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, sku varchar(20) NOT NULL UNIQUE, price numeric(10,2));
CREATE TABLE shop.orders (id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_id integer NOT NULL CONSTRAINT fk_cust REFERENCES shop.customers (id), placed timestamp, status varchar(10));
CREATE INDEX k_status ON shop.orders (status);
CREATE TABLE shop.order_items (order_id integer REFERENCES shop.orders (id), product_id integer REFERENCES shop.products (id),
  qty integer, PRIMARY KEY (order_id, product_id));
CREATE VIEW shop.big_orders AS SELECT o.id, c.email FROM shop.orders o JOIN shop.customers c ON c.id = o.customer_id;
CREATE FUNCTION shop.paid_orders() RETURNS SETOF integer LANGUAGE sql STABLE AS $$ SELECT id FROM shop.orders WHERE status = 'paid' $$;
CREATE FUNCTION shop.default_status() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN NEW.status := COALESCE(NEW.status, 'new'); RETURN NEW; END $$;
CREATE TRIGGER orders_status BEFORE INSERT ON shop.orders FOR EACH ROW EXECUTE FUNCTION shop.default_status();
