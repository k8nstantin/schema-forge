-- engine_postgresql.rules: a rewrite rule of a table, as the server writes it. Owner: postgresql.
CREATE TABLE engine_postgresql.rules (
  id          BIGINT NOT NULL PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,                                  -- issued by the database
  design      UUID NOT NULL REFERENCES cortex.designs (id) ON DELETE CASCADE DEFERRABLE INITIALLY DEFERRED,  -- the design it belongs to
  object      BIGINT NOT NULL,                                                                               -- the table
  name        TEXT NOT NULL CHECK (length(name) >= 1),                                                       -- its name
  definition  TEXT NOT NULL,                                                                                 -- the rule as the server writes it (CREATE RULE ...)
  UNIQUE (object, name) DEFERRABLE INITIALLY DEFERRED,
  UNIQUE (design, id),
  FOREIGN KEY (design, object) REFERENCES cortex.objects (design, id) ON DELETE CASCADE DEFERRABLE INITIALLY DEFERRED
);

CREATE INDEX rules_object ON engine_postgresql.rules (design, object);

COMMENT ON TABLE engine_postgresql.rules IS 'a rewrite rule of a table, as the server writes it.';
COMMENT ON COLUMN engine_postgresql.rules.id IS 'issued by the database';
COMMENT ON COLUMN engine_postgresql.rules.design IS 'the design it belongs to';
COMMENT ON COLUMN engine_postgresql.rules.object IS 'the table';
COMMENT ON COLUMN engine_postgresql.rules.name IS 'its name';
COMMENT ON COLUMN engine_postgresql.rules.definition IS 'the rule as the server writes it (CREATE RULE ...)';
